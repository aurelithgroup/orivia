import assert from 'node:assert/strict';
import {detectOpenNeed,entryGuidance} from '../workers/orivia-natural-entry.mjs';
const one=c=>[{role:'user',content:c}];
const student=detectOpenNeed(one('um idrk what i need but i am starting uni in a month and tbh idk what is being done...lol'));
assert.equal(student?.kind,'unsure_student');assert.match(student.guidance,/Do not assume they need a residence visa/);
const parent=detectOpenNeed(one('i just moved here with my kids.'));
assert.equal(parent?.kind,'family_arrival');assert.match(parent.guidance,/Do not presume school, visa/);
const brief=detectOpenNeed(one('residence id'));
assert.equal(brief?.kind,'ambiguous_document');assert.match(brief.guidance,/ONE short disambiguating/);
assert.equal(detectOpenNeed(one('I am starting uni next month and I need help with my residence visa')),null);
assert.equal(detectOpenNeed([{role:'user',content:'I am starting uni soon'},{role:'assistant',content:'What do you need?'},{role:'user',content:'transport'}]),null);
assert.equal(detectOpenNeed(one('I need help with transport to Heriot-Watt')),null);
assert.match(entryGuidance(one('residence id')),/NATURAL OPENING INTENT/);
console.log('Natural-language first contact: messy student, parent, brief fragment, no assumed visa: passed');
