import assert from 'node:assert/strict';
import {suggestChatTitle,titleForChat} from '../workers/trial-ui/chat-titles.mjs';
import {referenceLabel,renderCompactReferences} from '../workers/trial-ui/compact-references.mjs';
const u=content=>({role:'user',content});
assert.equal(suggestChatTitle([u('hi'),{role:'assistant',content:'Visa advice'},u('Can you find British schools in Sharjah?')]),'find British schools in Sharjah');
assert.equal(titleForChat({titled:true,title:'My own title',turns:[u('new subject')]}),'My own title');
assert.equal(suggestChatTitle([u('bonjour')],{language:'fr'}),'Nouvelle discussion');
assert.equal(suggestChatTitle([u('مرحبا')],{language:'ar'}),'محادثة جديدة');
for(const s of ['Email me at test@example.com','Call +971 50 123 4567','https://example.com/private','My name is Aisha'])assert.equal(suggestChatTitle([u(s)]),'New chat');
assert.ok(Array.from(suggestChatTitle([u('学校'.repeat(50))])).length<=48);
const doc={createTextNode:text=>({text}),createElement:()=>({attributes:{},setAttribute(k,v){this.attributes[k]=v}})};
const source={url:'https://spea.shj.ae/school',title:'School profile'};
const result=renderCompactReferences([{text:'British [99] '},{n:'3',src:source}],doc);
assert.equal(result[0].text,'British [99] ');
assert.equal(result[1].textContent,'spea.shj.ae');
assert.equal(result[1].href,source.url);
assert.match(result[1].attributes['aria-label'],/Source 3/);
assert.equal(referenceLabel({url:'javascript:alert(1)'}),null);
assert.equal(referenceLabel({url:'https://user:password@example.com'}),null);
assert.deepEqual(renderCompactReferences([{n:'7',src:{url:'http://example.com'}}],doc),[{text:'[7]'}]);
console.log('Chat presentation module checks passed');
