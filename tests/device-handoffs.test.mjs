import assert from 'node:assert/strict';
import {mapHandoffs,calendarHandoffInfo} from '../workers/orivia-device-handoffs.mjs';
import {tripActions} from '../workers/orivia-transport.mjs';

const destination='Heriot-Watt University Dubai, Dubai Knowledge Park, UAE';
const origin='Muwaileh, Sharjah, UAE';
const options=mapHandoffs({origin,destination,mode:'transit'});
assert.equal(options.length,3);
const geo=options.find(x=>x.id==='device');
assert.equal(geo.url,'geo:0,0?q='+encodeURIComponent(destination));
assert.equal(geo.mode,'place');
assert.doesNotMatch(geo.url,/Muwaileh|transit/,'geo is only a destination lookup, not routing');
const apple=new URL(options.find(x=>x.id==='apple').url);
assert.equal(apple.hostname,'maps.apple.com');
assert.equal(apple.searchParams.get('saddr'),origin);
assert.equal(apple.searchParams.get('daddr'),destination);
assert.equal(apple.searchParams.get('dirflg'),'r');
const google=new URL(options.find(x=>x.id==='google').url);
assert.equal(google.hostname,'www.google.com');
assert.equal(google.searchParams.get('origin'),origin);
assert.equal(google.searchParams.get('destination'),destination);
assert.equal(google.searchParams.get('travelmode'),'transit');
assert.equal(new URL(mapHandoffs({destination,mode:'driving'}).find(x=>x.id==='apple').url).searchParams.get('dirflg'),'d');
assert.deepEqual(mapHandoffs({origin,mode:'driving'}),[]);
for(const mode of ['transit','driving'])for(const x of mapHandoffs({origin,destination,mode})){
 if(x.url.startsWith('https:'))assert.ok(['maps.apple.com','www.google.com'].includes(new URL(x.url).hostname));
 else assert.match(x.url,/^geo:0,0\?q=/);
}
const plan={dest:{name:'Heriot-Watt University Dubai',address:destination},origin,pref:'time'};
const links=tripActions(plan).actions;
for(const domain of ['maps.apple.com','www.google.com'])assert.ok(links.some(x=>x.url.includes(domain)));
assert.ok(links.some(x=>x.url.startsWith('geo:')));
assert.ok(links.some(x=>x.url.includes('travelmode=transit')));
assert.ok(links.some(x=>x.url.includes('travelmode=driving')));
assert.match(tripActions(plan).context,/Apple Maps and Google Maps/);
const calendar=calendarHandoffInfo();
assert.equal(calendar.format,'text/calendar');
assert.equal(calendar.autoAdded,false);
assert.equal(calendar.requiresConfirmation,true);
assert.match(calendar.explanation,/confirm Save/);
console.log('Device handoffs: destination lookup, Apple and Google routes, explicit calendar import contract passed');
